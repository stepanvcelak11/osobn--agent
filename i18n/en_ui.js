// Quest texts are filled with the hero's name, province and feminine endings ({hrdina}, {kraj}, {a})
// before they reach the page, so the plain dictionary can't find them. Rebuild the template from the
// translated content dictionaries and match the filled text against it.
const TPL = [];
for (const f of ['en_systems.js', 'en_world.js']) {
  try {
    const m = await import(`./${f}`);
    for (const [k, v] of Object.entries(m.default ?? {})) if (v && /\{(hrdina|kraj|a)\}/.test(k)) TPL.push({ k: k.replace(/\s+/g, ' ').trim(), v });
  } catch { /* missing dictionary */ }
}
const esc = (s) => s.replace(/[.*+?^$()|[\]\\]/g, '\\$&');
function compile(t) {
  if (t.re) return t.re;
  const names = [];
  const src = esc(t.k).replace(/\\?\{(hrdina|kraj|a)\\?\}/g, (_, n) => { if (n === 'a') return 'a?'; names.push(n); return '(.+?)'; });
  t.names = names;
  t.re = new RegExp(`^${src}$`);
  return t.re;
}
class Unfill extends RegExp {
  [Symbol.match](s) {
    if (!/[A-Za-zÀ-ž]/.test(s)) return null;
    for (const t of TPL) {
      const r = compile(t).exec(s);
      if (r) return Object.assign([s], { t, r });
    }
    return null;
  }
}
